inline const style::color *FindColor(const char *name) {
	if (!name) {
		return nullptr;
	}
	const auto *table = Colors();
	for (int i = 0; i != kColorCount; ++i) {
		if (!std::strcmp(table[i].name, name)) {
			return table[i].value;
		}
	}
	return nullptr;
}

