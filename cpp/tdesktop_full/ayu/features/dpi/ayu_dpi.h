#pragma once

#include <QtCore/QString>

// DPI-обход блокировок Telegram через локальный SOCKS5-прокси (ayu-dpi).
//
// Модуль владеет отдельным процессом `ayu-dpi.exe` и говорит клиенту, идти ли
// через него. Прокси оператора он не трогает: настройка в `Core::Settings`
// остаётся его собственной, а переопределение ставится в `Core::Application`
// (только в памяти), откуда его читают сетевые потребители. Поэтому включение
// обхода не переписывает чужие настройки и не появляется в списке прокси в UI.
namespace Ayu::Dpi {

// Приводит состояние обхода в соответствие с настройкой: поднимает процесс и
// переключает клиент на него, либо гасит процесс и возвращает прямой маршрут.
// Идемпотентно. Зовётся при старте клиента и при переключении настройки.
void applyFromSettings();

// Гасит процесс, если он запущен этим клиентом, и снимает переопределение.
// Зовётся при выходе, чтобы не оставить висящий процесс, который займёт порт.
void stop();

// Работает ли обход прямо сейчас (процесс поднят и переопределение стоит).
[[nodiscard]] bool running();

// Причина, по которой обход не удалось поднять: для журнала и подсказки в UI.
[[nodiscard]] const QString &lastError();

} // namespace Ayu::Dpi
